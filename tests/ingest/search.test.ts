import { describe, expect, it } from "vitest";
import { FactIndex, bigrams } from "../../src/lib/ingest/search";
import type { DocFact } from "../../src/lib/live/contract";

// B-plan.md를 haiku로 뽑은 결과 (검색용 다른 표현 없이) — 정리된 문장으로도 잘 찾는지
const PLAN: [string, string, string][] = [
  ["갈피는 팀 회의에 같이 앉아 있는 AI 팀원 \"미티\"를 만든다.", "\"한 줄\" 절", "갈피는 팀 회의에 같이 앉아 있는 AI 팀원 \"미티\"를 만든다."],
  ["미티는 팀이 지금까지 정한 결정을 전부 기억한다.", "\"한 줄\" 절", "미티는 팀이 지금까지 정한 걸 전부 기억하고, 회의 중에 필요할 때 목소리로 끼어든다."],
  ["대상 사용자는 서기도 PM도 없는 작은 팀이다.", "\"누구를 위한 건가\" 절", "서기도 PM도 없는 작은 팀. 대학생 팀 프로젝트, 초기 스타트업."],
  ["끼어들기 강도는 상·중·하 세 단계다.", "\"끼어들기 강도\" 절", "세 단계다."],
  ["상 강도는 말이 0.3초만 끊겨도 바로 말한다.", "\"끼어들기 강도\" 절", "상: 말이 0.3초만 끊겨도 바로 말한다."],
  ["중 강도는 0.8초 이상 끊기면 말한다.", "\"끼어들기 강도\" 절", "중: 0.8초 이상 끊기면 말한다."],
  ["하 강도에서는 먼저 말하지 않고 화면에 손만 든다.", "\"끼어들기 강도\" 절", "하: 먼저 말하지 않고 화면에 손만 든다."],
  ["끼어들기 강도를 낮추는 것은 말로 바로 할 수 있다.", "\"끼어들기 강도\" 절", "강도를 낮추는 건 말로 바로 된다(\"끼어들지 마\")."],
  ["끼어들기 강도를 올리는 것은 화면에서 확인해야 한다.", "\"끼어들기 강도\" 절", "올리는 건 화면에서 확인해야 한다."],
  ["확정된 결정과 어긋나는 말이 나오면 미티가 말하며, 근거를 같이 보여준다.", "\"언제 말하나\" 절", "확정된 결정과 어긋나는 말이 나왔을 때 (근거를 같이 보여준다)"],
  ["기존 기록은 미티가 읽기만 하며 바꾸지 않는다.", "\"기록과 권한\" 절", "기존 기록은 읽기만 한다."],
  ["로컬 모드에서는 음성과 회의 내용이 기기 밖으로 나가지 않는다.", "\"기록과 권한\" 절", "로컬 모드에선 음성과 회의 내용이 기기 밖으로 나가지 않는다."],
  ["설정을 바꾸는 말은 등록된 팀원 목소리에서만 받는다.", "\"기록과 권한\" 절", "설정을 바꾸는 말은 등록된 팀원 목소리에서만 받는다."],
];
const facts: DocFact[] = PLAN.map(([text, loc, quote], i) => ({ id: `p#${i + 1}`, docId: "p", kind: "decision", text, loc, quote }));
const index = new FactIndex(facts);
const top3 = (q: string) => index.search(q, 3).map((r) => r.fact.text);

describe("글자 2-gram", () => {
  it("띄어쓰기·문장부호를 지우고 자른다", () => {
    expect(bigrams("세 단계.")).toEqual(["세단", "단계"]);
    expect(bigrams("AI")).toEqual(["ai"]);
    expect(bigrams("")).toEqual([]);
  });
});

describe("시나리오 B 발표 문장 → 기획 사실", () => {
  it("다섯 단계 → 세 단계", () => {
    expect(top3("끼어드는 강도는 다섯 단계로 조절할 수 있고요")).toContain("끼어들기 강도는 상·중·하 세 단계다.");
  });
  it("외부 서버 → 로컬 모드", () => {
    expect(top3("회의 내용은 전부 외부 서버로 보내서 처리합니다.")).toContain("로컬 모드에서는 음성과 회의 내용이 기기 밖으로 나가지 않는다.");
  });
  it("정한 걸 기억 → 미티는 전부 기억", () => {
    expect(top3("팀이 지금까지 정한 걸 전부 기억하고 있다가, 회의 중에 어긋나는 순간 말해 줍니다.")).toContain("미티는 팀이 지금까지 정한 결정을 전부 기억한다.");
  });
  it("점수는 높은 순, k개까지", () => {
    const r = index.search("강도", 2);
    expect(r).toHaveLength(2);
    expect(r[0].score).toBeGreaterThanOrEqual(r[1].score);
  });
});

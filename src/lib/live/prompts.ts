// 대답 글에서 "웹: 검색어" 줄을 떼어 낸다 (소리로 읽히면 안 된다)
export function splitWebQuery(lines: string[]): { lines: string[]; query?: string } {
  let query: string | undefined;
  const rest = lines.filter((l) => {
    const m = l.match(/^웹\s*[:：]\s*(.+)$/);
    if (m) query ??= m[1].trim();
    return !m;
  });
  return { lines: rest, ...(query ? { query } : {}) };
}


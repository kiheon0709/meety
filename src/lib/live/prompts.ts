export function parseTemplates(text: string): Map<string, string> {
  const out = new Map<string, string>();
  for (const raw of text.split(/\r?\n/)) {
    const m = raw.match(/^\s*[-*]?\s*\[?([^\]|\s]+)\]?\s*\|\s*(.+?)\s*$/);
    if (m) out.set(m[1], m[2]);
  }
  return out;
}


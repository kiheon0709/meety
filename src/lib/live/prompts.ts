// 대답 글에서 문장들과 "근거:" 줄을 나눈다
export function parseLines(text: string): { lines: string[]; ids: string[] } {
  const lines: string[] = [];
  let ids: string[] = [];
  for (const raw of text.split(/\r?\n/)) {
    const t = raw.trim().replace(/^[-*•]\s*/, "");
    if (!t) continue;
    // 근거 줄을 대답 끝에 붙여 쓰는 일이 있다("…돼요. 근거:" — 11/1 자기소개 확인) → 떼어 낸다. 끝에 붙은 "근거:" 뒤에 한글이 오면 대답 속 말이라 그대로
    const lead = t.match(/^근거\s*[:：]\s*(.*)$/);
    const tail = lead ? null : t.match(/^(.*?)\s+근거\s*[:：]\s*([^가-힣]*)$/);
    const idText = lead?.[1] ?? tail?.[2];
    if (idText !== undefined) ids = idText.split(/[,\s]+/).map((x) => x.replace(/[\[\]]/g, "").trim()).filter(Boolean);
    if (!lead) lines.push(tail ? tail[1] : t);
  }
  return { lines, ids };
}

export function parseVerify(text: string): { ok: boolean; reason: string; ids: string[] } {
  const { lines, ids } = parseLines(text);
  return { ok: /^OK\b/i.test(lines[0] ?? ""), reason: lines.slice(1).join(" ") || lines[0] || "", ids };
}


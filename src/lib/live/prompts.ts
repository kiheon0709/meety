const nums = z.array(z.union([z.number(), z.string()]).transform((x) => Number(String(x).replace(/\D/g, "")))).catch([]);
const str = z.string().nullable().catch("").transform((x) => x ?? "");

export const WatchOut = z.object({
  conflict: z
    .object({ found: z.boolean().catch(false), node_ids: ids, fact_ids: ids, said: str, against: str })
    .catch({ found: false, node_ids: [], fact_ids: [], said: "", against: "" }),
  agreement: z
    .object({ found: z.boolean().catch(false), title: str, from: z.string().nullable().catch(null), to: str, utt_ids: nums })
    .catch({ found: false, title: "", from: null, to: "", utt_ids: [] }),
  call: z
    .object({ addressed: z.boolean().catch(false), want: z.enum(["none", "question", "speak_pending"]).catch("none"), question: str })
    .catch({ addressed: false, want: "none" as const, question: "" }),
  resolved: ids,
});
export type WatchResult = z.infer<typeof WatchOut>;

